import {randomBytes} from 'node:crypto';
import {clientKey,origin,account} from './clients.js';
import {decode} from './delivery.js';
import {redis} from './redis.js';
export const shortKey=id=>'diginest:v1:shortlink:'+id;
export async function shortenLinks(c,urls){
 if(!Array.isArray(urls)||urls.length<1||urls.length>100||urls.some(u=>typeof u!=='string'||u.length>8000))throw Error('Provide 1–100 generated customer links.');
 const base=origin(c);if(!base)throw Error('The provider must configure the output domain.');
 const prefix='/b/'+c.slug+'/subscription/new/';const env={LINK_KEY:clientKey(c)};
 const records=await Promise.all(urls.map(async value=>{
  try{const u=new URL(value);if(u.origin!==base||u.username||u.password||u.search||u.hash||!u.pathname.startsWith(prefix))throw Error();const code=u.pathname.slice(prefix.length);if(!/^[A-Za-z0-9_-]{30,7000}$/.test(code))throw Error();const p=await decode(code,env);if(p.e<=Date.now())throw Error();return {username:c.username,slug:c.slug,code,expiresAt:p.e};}catch{throw Error('Use active customer links generated by your own account.');}
 }));
 // Reserve and write the entire batch atomically so a collision cannot replace an existing link.
 const script=`for i=1,#KEYS do if redis.call('EXISTS',KEYS[i]) == 1 then return 0 end end for i=1,#KEYS do redis.call('SET',KEYS[i],ARGV[2*i-1],'PX',ARGV[2*i]) end return 1`;
 for(let attempt=0;attempt<3;attempt++){
  const ids=records.map(()=>randomBytes(9).toString('base64url'));const now=Date.now();if(records.some(r=>r.expiresAt<=now))throw Error('A customer link has expired. Create a new batch.');
  const result=await redis('EVAL',script,String(ids.length),...ids.map(shortKey),...records.flatMap(r=>[JSON.stringify(r),String(r.expiresAt-now)]));
  if(result===1)return records.map((r,i)=>({url:base+'/s/'+ids[i],longUrl:urls[i],expiresAt:new Date(r.expiresAt).toISOString()}));
 }
 throw Error('Could not reserve short links. Try again.');
}
export async function resolveShortLink(id){
 if(!/^[A-Za-z0-9_-]{12}$/.test(id))return null;
 const raw=await redis('GET',shortKey(id));if(!raw)return null;const r=JSON.parse(raw);
 if(!Number.isSafeInteger(r.expiresAt)||r.expiresAt<=Date.now()||typeof r.code!=='string'||! /^[A-Za-z0-9_-]{30,7000}$/.test(r.code))return null;
 const c=await account(r.username);if(!c||c.slug!==r.slug)return null;const base=origin(c);if(!base)return null;
 // Recheck encrypted ownership and expiry, including LINK_KEY changes.
 try{const p=await decode(r.code,{LINK_KEY:clientKey(c)});if(p.e!==r.expiresAt||p.e<=Date.now())return null;}catch{return null;}
 return {origin:base,url:base+'/b/'+c.slug+'/subscription/new/'+r.code};
}
